export function hashPassword(password: string, salt = 'sigap-ppa-sidoarjo-demo-salt'): string {
  const derived = crypto.scryptSync(password, salt, 32).toString('hex');
  return `${salt}:${derived}`;
}

export function verifyPassword(password: string, storedHash: string): boolean {
  const [salt, originalHex] = storedHash.split(':');
  if (!salt || !originalHex) return false;
  const candidateHex = crypto.scryptSync(password, salt, 32).toString('hex');
  return crypto.timingSafeEqual(Buffer.from(originalHex, 'hex'), Buffer.from(candidateHex, 'hex'));
}

